// `pnpm contracts:gen` — Zod contracts (web/lib/contracts) → contracts/openapi.json → Pydantic
// models for the worker and the agent tools (DESIGN §3, decision #21). Deterministic: run it after
// changing a contract and commit the outputs; CI fails if they're stale.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildOpenApi } from "../web/lib/contracts/openapi";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OPENAPI = path.join(root, "contracts/openapi.json");
const TARGETS = [
  path.join(root, "worker/src/pandabase_worker/contracts.py"),
  path.join(root, "agent/tools/src/pandabase_tools/contracts.py"),
];
const HEADER =
  "# Generated by `pnpm contracts:gen` from contracts/openapi.json (web/lib/contracts). Do not edit.";

writeFileSync(OPENAPI, JSON.stringify(buildOpenApi(), null, 2) + "\n");
console.log(`wrote ${path.relative(root, OPENAPI)}`);

// datamodel-code-generator and ruff are pinned in worker/uv.lock (dev group).
const uv = (...args: string[]) =>
  execFileSync("uv", ["run", "--project", "worker", "--locked", ...args], {
    cwd: root,
    stdio: ["ignore", "inherit", "inherit"],
  });
const tmp = mkdtempSync(path.join(tmpdir(), "pandabase-contracts-"));
try {
  const out = path.join(tmp, "contracts.py");
  uv(
    "datamodel-codegen",
    "--input",
    OPENAPI,
    "--input-file-type",
    "openapi",
    "--output",
    out,
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.14",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-annotated",
    "--field-constraints",
    "--enum-field-as-literal",
    "all",
    "--collapse-root-models",
    "--use-schema-description",
    "--use-double-quotes",
    "--disable-timestamp",
    "--custom-file-header",
    HEADER,
    "--formatters",
    "ruff-format",
  );
  // Same ruff settings as both Python projects (line length, py314), so their checks pass.
  uv("ruff", "check", "--fix", "--quiet", "--config", "worker/pyproject.toml", out);
  uv("ruff", "format", "--quiet", "--config", "worker/pyproject.toml", out);
  const code = readFileSync(out, "utf8");
  for (const target of TARGETS) {
    writeFileSync(target, code);
    console.log(`wrote ${path.relative(root, target)}`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
